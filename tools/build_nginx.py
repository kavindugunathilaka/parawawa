"""nginx site config for hosting on a Linux VPS, generated from vercel.json so both stay in sync.

Writes deploy/nginx/parawawa.conf. Run via tools/build.py (or alone: python tools/build_nginx.py).
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

DOMAIN = 'parawawa.lk'
WEBROOT = '/var/www/parawawa/current'
QUOTE_PORT = 3005

SECURITY = '''    add_header X-Content-Type-Options "nosniff" always;
    add_header Referrer-Policy "strict-origin-when-cross-origin" always;
    add_header X-Frame-Options "SAMEORIGIN" always;
    add_header Permissions-Policy "camera=(), microphone=(), geolocation=()" always;'''


def block(match, body):
    """A location with the security headers repeated (nginx drops server-level add_header inside a location that sets its own)."""
    return f'''  location {match} {{
{SECURITY}
{body}
  }}
'''


def main():
    cfg = json.load(open('vercel.json', encoding='utf-8'))

    redirects = ''.join(
        f"  location = {r['source']} {{ return {301 if r.get('permanent', True) else 302} {r['destination']}; }}\n"
        for r in cfg['redirects'])

    out = f'''# Generated by tools/build_nginx.py from vercel.json - do not edit by hand.
# Install: sudo cp deploy/nginx/parawawa.conf /etc/nginx/sites-available/parawawa.conf
#          sudo ln -s /etc/nginx/sites-available/parawawa.conf /etc/nginx/sites-enabled/
#          sudo nginx -t && sudo systemctl reload nginx
#          sudo certbot --nginx -d {DOMAIN} -d www.{DOMAIN}     (adds HTTPS + http->https redirect)

limit_req_zone $binary_remote_addr zone=parawewa_quote:10m rate=6r/m;

# www -> apex
server {{
  listen 80;
  listen [::]:80;
  server_name www.{DOMAIN};
  return 301 https://{DOMAIN}$request_uri;
}}

server {{
  listen 80;
  listen [::]:80;
  server_name {DOMAIN};

  root {WEBROOT};
  index index.html;
  charset utf-8;
  absolute_redirect off;
  server_tokens off;
  error_page 404 /404.html;

  gzip on;
  gzip_comp_level 6;
  gzip_min_length 512;
  gzip_vary on;
  gzip_types text/css application/javascript application/json image/svg+xml application/xml text/xml text/plain application/rss+xml;

{SECURITY}

  # ---- redirects from the old WordPress site and renamed pages (same as vercel.json)
{redirects}
  # ---- quote form -> Node service (deploy/quote-server.js)
  location = /api/quote {{
    limit_req zone=parawewa_quote burst=5 nodelay;
    limit_req_status 429;
    client_max_body_size 16k;
    proxy_pass http://127.0.0.1:{QUOTE_PORT};
    proxy_set_header Host $host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
  }}
  location /api/ {{ return 404; }}

  # ---- Let's Encrypt (certbot) domain check
  location ^~ /.well-known/acme-challenge/ {{ default_type text/plain; try_files $uri =404; }}

  # ---- never served: sources, build tools, server files
  location ~ ^/(tools|content|deploy|\\.git)(/|$) {{ return 404; }}
  location ~ /\\. {{ return 404; }}
  location ~* ^/(README\\.md|vercel\\.json|\\.vercelignore|.*\\.py)$ {{ return 404; }}

  # ---- caching (same as vercel.json)
{block('~ ^/(style\\.css|app\\.js|articles-meta\\.js)$', '    add_header Cache-Control "public, max-age=31536000, immutable" always;')}
{block('~ ^/assets/(fa/fa-subset|fonts/fonts)\\.css$', '    add_header Cache-Control "public, max-age=31536000, immutable" always;')}
{block('/assets/fonts/', '    add_header Cache-Control "public, max-age=2592000, stale-while-revalidate=86400" always;')}
{block('/assets/fa/', '    add_header Cache-Control "public, max-age=86400, stale-while-revalidate=604800" always;')}
{block('/assets/', '    add_header Cache-Control "public, max-age=604800, stale-while-revalidate=86400" always;')}
{block('~ \\.html$', '    add_header Cache-Control "public, max-age=0, must-revalidate" always;')}
  location / {{
    try_files $uri $uri/ =404;
  }}
}}
'''
    os.makedirs('deploy/nginx', exist_ok=True)
    open('deploy/nginx/parawawa.conf', 'w', encoding='utf-8', newline='\n').write(out)
    print('built deploy/nginx/parawawa.conf (%d redirects)' % len(cfg['redirects']))


if __name__ == '__main__':
    main()
